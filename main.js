// Datos del idioma (bandera y código del botón)
const LANGS = {
    en: { name: "EN", flag: "🇺🇸" },
    es: { name: "ES", flag: "🇭🇳" }
};

// Textos que no viven en el HTML
const EN_EXTRA = {
    read_more: "Read more",
    read_less: "Read less",
    wa_msg: "Hello, I would like more information about your services."
};

function initializeSite() {

    /* ======================================================
       1. SISTEMA DE IDIOMAS
       ====================================================== */
    const EN = { ...EN_EXTRA };

    // Captura el inglés directamente del HTML
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const k = el.dataset.i18n;
        if (!(k in EN)) EN[k] = el.innerHTML.trim();
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const k = el.dataset.i18nPlaceholder;
        if (!(k in EN)) EN[k] = el.getAttribute('placeholder');
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const k = el.dataset.i18nAria;
        if (!(k in EN)) EN[k] = el.getAttribute('aria-label');
    });
    EN.meta_title = document.title;
    const metaDesc = document.querySelector('meta[name="description"]');
    EN.meta_desc = metaDesc ? metaDesc.content : '';

    const dictionaries = { en: EN, es: { ...EN, ...ES } };
    let currentLang = 'en';

    const t = (key) => dictionaries[currentLang][key] ?? EN[key] ?? '';

    function updateToggleLabels() {
        document.querySelectorAll('.testi-toggle').forEach(btn => {
            const expanded = btn.dataset.expanded === 'true';
            btn.textContent = t(expanded ? 'read_less' : 'read_more');
        });
    }

    function setLanguage(lang) {
        if (!dictionaries[lang]) lang = 'en';
        currentLang = lang;
        document.documentElement.lang = lang;

        // Textos
        document.querySelectorAll('[data-i18n]').forEach(el => {
            el.innerHTML = t(el.dataset.i18n);
        });
        // Placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
        });
        // aria-label / title
        document.querySelectorAll('[data-i18n-aria]').forEach(el => {
            const txt = t(el.dataset.i18nAria);
            el.setAttribute('aria-label', txt);
            el.setAttribute('title', txt);
        });
        // Título y meta descripción
        document.title = t('meta_title');
        if (metaDesc) metaDesc.content = t('meta_desc');

        // Botones de idioma (escritorio y móvil)
        document.querySelectorAll('.lang-switch').forEach(btn => {
            btn.querySelector('.lang-flag').textContent = LANGS[lang].flag;
            btn.querySelector('.lang-text').textContent = LANGS[lang].name;
        });

        // "Leer más / Leer menos"
        updateToggleLabels();

        // Mensaje de WhatsApp en el idioma activo
        const wa = document.getElementById('wa-float');
        if (wa) {
            const base = wa.href.split('?')[0];
            wa.href = base + '?text=' + encodeURIComponent(t('wa_msg'));
        }

        try { localStorage.setItem('gc-lang', lang); } catch (e) {}
    }

    document.querySelectorAll('.lang-switch').forEach(btn => {
        btn.addEventListener('click', () => {
            setLanguage(currentLang === 'en' ? 'es' : 'en');
        });
    });

    // "Read more / Read less" de los testimonios
    document.querySelectorAll('.testi-toggle').forEach(btn => {
        btn.dataset.expanded = 'false';
        btn.addEventListener('click', () => {
            const body = btn.parentElement.querySelector('.testi-body');
            const expanded = body.classList.toggle('line-clamp-[10]') === false;
            btn.dataset.expanded = String(expanded);
            btn.textContent = t(expanded ? 'read_less' : 'read_more');
        });
    });

    // Idioma inicial: el guardado por el visitante, o el de su navegador
    let initial = 'en';
    try { initial = localStorage.getItem('gc-lang') || ''; } catch (e) {}
    if (!initial) {
        initial = (navigator.language || 'en').toLowerCase().startsWith('es') ? 'es' : 'en';
    }
    if (initial !== 'en') setLanguage(initial);

    /* ======================================================
       2. ICONOS LUCIDE
       ====================================================== */
    if (window.lucide) {
        lucide.createIcons();
    }

    /* ======================================================
       3. NAVBAR
       ====================================================== */
    const navbar = document.getElementById('navbar');
    window.addEventListener('scroll', () => {
        if (!navbar) return;
        if (window.scrollY > 50) {
            navbar.classList.add('bg-slate-900/95', 'backdrop-blur-md', 'shadow-lg');
        } else {
            navbar.classList.remove('bg-slate-900/95', 'backdrop-blur-md', 'shadow-lg');
        }
    });

    /* ======================================================
       4. ANIMACIONES GSAP
       ====================================================== */
    if (window.gsap && window.ScrollTrigger) {
        gsap.registerPlugin(ScrollTrigger);

        gsap.from('#hero .relative.z-10 > div > *', {
            y: 30,
            opacity: 0,
            duration: 1,
            stagger: 0.2,
            ease: "power3.out"
        });

        document.querySelectorAll('#about, #services, #why-us, #testimonials, #ceo, #contact').forEach((section) => {
            gsap.from(section, {
                scrollTrigger: {
                    trigger: section,
                    start: "top 85%",
                    toggleActions: "play none none none"
                },
                y: 30,
                opacity: 0,
                duration: 1,
                clearProps: "all"
            });
        });

        const cards = document.querySelectorAll('#services .group');
        if (cards.length > 0) {
            gsap.from(cards, {
                scrollTrigger: {
                    trigger: '#services',
                    start: "top 75%",
                    toggleActions: "play none none none"
                },
                y: 40,
                opacity: 0,
                duration: 0.8,
                stagger: 0.1,
                ease: "power2.out",
                clearProps: "all"
            });
        }
    }
}

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initializeSite);
} else {
    initializeSite();
}
